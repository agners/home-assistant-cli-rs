use crate::cmd::helpers::leaf;
use crate::cmd::logs::{add_logs_flags, run_logs};
use crate::cobra::Command;

pub fn command() -> Command {
    add_logs_flags(
        leaf("logs")
            .aliases(&["log", "lg"])
            .short("View the log output of the Home Assistant DNS server")
            .long(
                "
Allowing you to look at the log output generated by the Home Assistant DNS server.
",
            )
            .example(
                "
  ha dns logs
",
            ),
    )
    .run(run_logs("dns"))
}
