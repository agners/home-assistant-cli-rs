use crate::cmd::completions;
use crate::cmd::helpers::debug_args;
use crate::cmd::logs::{add_logs_flags, process_logs_flags, send_and_stream};
use crate::cobra::{Args, Command};

pub fn command() -> Command {
    add_logs_flags(
        Command::new("logs [slug]")
            .aliases(&["log", "lg"])
            .short("View the log output of a running Home Assistant app")
            .long(
                "
Allowing you to look at the log output generated by a Home Assistant app.
",
            )
            .example(
                "
  ha apps logs core_ssh
",
            )
            .valid_args(completions::apps())
            .args(Args::Exact(1)),
    )
    .run(|ctx| {
        debug_args(ctx);
        let request = process_logs_flags("addons/{slug}", ctx);
        send_and_stream(request.map(|r| r.path_param("slug", ctx.arg(0))))
    })
}
